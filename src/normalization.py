"""Phase 4 -- put every capture into one comparable coordinate frame.

Full rationale and the exact maths: docs/NORMALIZATION.md.

The pipeline in brief
---------------------
    raw vertices
      -> [1] to face-local space   (exact; undoes camera distance and head pose)
      -> [2] to the canonical Looksmatch frame  (signed axis permutation)
      -> [3] translate to a chosen origin
      -> [4] divide by a chosen scale reference
      -> [5] optional Procrustes refinement against a cohort mean shape

Why step [1] is exact, not estimated
------------------------------------
``ARFaceGeometry.vertices`` are expressed relative to the ``ARFaceAnchor``, not
to the camera. ARKit has already solved head pose, so a face-local capture is
ALREADY free of camera distance, translation and rotation. There is nothing to
estimate. If the exporter baked the anchor transform into the vertices (i.e.
exported world space), we invert that transform to get back.

So "rotation normalisation" here is not a fitting problem -- it is a matter of
knowing which ARKit axis is which, which is a fixed property of the format. That
is DETECTED ONCE from your real data (with reported evidence you can eyeball),
never assumed. See :class:`AxisConvention`.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable, Sequence

import numpy as np
from scipy.spatial import cKDTree

from .config import CONFIG_DIR, RAW_DIR, ensure_dirs
from .data_loader import FaceCapture, load_all, load_capture

AXES_PATH = CONFIG_DIR / "axis_convention.json"

# Canonical Looksmatch frame, right-handed:
#   +X = subject's LEFT      +Y = superior (up)      +Z = anterior (out of face)
# Check: X x Y = Z holds for (left, up, anterior) when viewed from in front.
CANONICAL_AXES = ("left", "superior", "anterior")


# ==========================================================================
# Axis convention
# ==========================================================================

@dataclass
class AxisConvention:
    """Which raw ARKit axis (and sign) corresponds to each canonical direction.

    ``left = (axis_index, sign)`` means: canonical +X (subject's left) equals
    ``sign * raw[:, axis_index]``.
    """

    left: tuple[int, int]
    superior: tuple[int, int]
    anterior: tuple[int, int]
    evidence: dict = field(default_factory=dict)
    confirmed_by_user: bool = False

    # -- matrix form -------------------------------------------------------

    def matrix(self) -> np.ndarray:
        """``(3, 3)`` matrix R with ``canonical = raw @ R.T``."""
        rot = np.zeros((3, 3), dtype=np.float64)
        for row, (axis, sign) in enumerate((self.left, self.superior, self.anterior)):
            rot[row, axis] = float(sign)
        return rot

    def is_right_handed(self) -> bool:
        return bool(np.linalg.det(self.matrix()) > 0)

    def apply(self, points: np.ndarray) -> np.ndarray:
        return np.asarray(points, dtype=np.float64) @ self.matrix().T

    # -- persistence -------------------------------------------------------

    def to_dict(self) -> dict:
        return {
            "_README": (
                "Which raw ARKit axis maps to each canonical Looksmatch direction. "
                "Canonical frame is right-handed: +X subject's left, +Y superior, "
                "+Z anterior. Format: [raw_axis_index, sign]. Generated by "
                "`python -m src.normalization detect`; set confirmed_by_user true "
                "once you have eyeballed the result in the 3D viewer."
            ),
            "left": list(self.left),
            "superior": list(self.superior),
            "anterior": list(self.anterior),
            "confirmed_by_user": self.confirmed_by_user,
            "evidence": self.evidence,
        }

    def save(self, path: Path | None = None) -> Path:
        path = path or AXES_PATH
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.to_dict(), indent=2), encoding="utf-8")
        return path

    @classmethod
    def load(cls, path: Path | None = None) -> "AxisConvention | None":
        path = path or AXES_PATH
        if not path.exists():
            return None
        blob = json.loads(path.read_text(encoding="utf-8"))
        return cls(
            left=tuple(blob["left"]),
            superior=tuple(blob["superior"]),
            anterior=tuple(blob["anterior"]),
            evidence=blob.get("evidence", {}),
            confirmed_by_user=bool(blob.get("confirmed_by_user", False)),
        )

    def describe(self) -> str:
        names = "XYZ"
        parts = [
            f"  subject's left  = {'+' if s > 0 else '-'}{names[a]}"
            for a, s in (self.left,)
        ]
        parts.append(f"  superior (up)   = {'+' if self.superior[1] > 0 else '-'}{names[self.superior[0]]}")
        parts.append(f"  anterior (out)  = {'+' if self.anterior[1] > 0 else '-'}{names[self.anterior[0]]}")
        parts.append(f"  right-handed    = {self.is_right_handed()}")
        return "\n".join(parts)


def _mirror_symmetry_error(points: np.ndarray, axis: int) -> float:
    """RMS nearest-neighbour error after mirroring across the plane normal to
    ``axis`` through the centroid, normalised by centroid size.

    Low error means the mesh is bilaterally symmetric about that axis, which is
    what identifies the left-right axis of a face.
    """
    centred = points - points.mean(axis=0)
    scale = float(np.sqrt((centred ** 2).sum(axis=1).mean()))
    if scale == 0:
        return np.inf
    mirrored = centred.copy()
    mirrored[:, axis] *= -1.0
    distances, _ = cKDTree(centred).query(mirrored, k=1)
    return float(np.sqrt((distances ** 2).mean()) / scale)


def _skewness(values: np.ndarray) -> float:
    centred = values - values.mean()
    sigma = centred.std()
    return float((centred ** 3).mean() / sigma ** 3) if sigma > 0 else 0.0


def detect_axis_convention(captures: Sequence[FaceCapture]) -> AxisConvention:
    """Work out the ARKit axis convention from real captures, with evidence.

    Detection rules, in order of reliability:

    LEFT-RIGHT axis
        The axis whose mirror plane leaves the mesh most self-similar (faces are
        bilaterally symmetric; the other two axes are not). Decided by
        :func:`_mirror_symmetry_error`, which is a property of the geometry, not
        an assumption.
    LEFT-RIGHT sign
        From ``ARFaceAnchor.leftEyeTransform`` vs ``rightEyeTransform`` when the
        export has them -- these are named by Apple, so the sign is definitive.
        WITHOUT them the sign is UNRESOLVED: we pick one and flag it, and
        side-specific ("left cheek" vs "right cheek") features are suppressed
        because they would be mirrored. Bilateral and midline features are
        unaffected.
    ANTERIOR axis and sign
        Of the two remaining axes, the nose is a protruding tail, so the
        anterior axis is the one with the larger absolute skewness, and the tail
        points anteriorly (sign = sign of the skew).
    SUPERIOR axis and sign
        The remaining axis. Sign from the eye midpoint sitting above the mesh
        centroid when eye transforms exist; otherwise from the face being
        broader superiorly (forehead/cheekbones) than inferiorly (the chin
        tapers).
    """
    if not captures:
        raise ValueError("need at least one capture to detect the axis convention")

    evidence: dict = {"n_captures": len(captures)}

    # ---- left-right axis: bilateral symmetry ----------------------------
    sym_errors = np.zeros(3)
    for capture in captures:
        local = to_face_local(capture)
        for axis in range(3):
            sym_errors[axis] += _mirror_symmetry_error(local, axis)
    sym_errors /= len(captures)
    lr_axis = int(np.argmin(sym_errors))
    evidence["mirror_symmetry_error_per_axis"] = [round(float(v), 5) for v in sym_errors]
    evidence["left_right_axis"] = lr_axis
    ordered = np.sort(sym_errors)
    # How decisively the best axis beat the runner-up. Capped for readability:
    # a synthetically perfect mesh drives the denominator to ~0 and the ratio to
    # ~1e14, which is noise in the report rather than information.
    margin = float(ordered[1] / ordered[0]) if ordered[0] > 1e-12 else float("inf")
    evidence["left_right_margin"] = round(margin, 3) if margin < 1e6 else ">1e6 (near-perfect symmetry)"

    # ---- left-right sign: eye transforms are definitive ------------------
    lr_sign = 1
    eye_votes: list[float] = []
    for capture in captures:
        eyes = capture.eye_positions()
        if eyes is None:
            continue
        left_eye, right_eye = eyes
        eye_votes.append(float(left_eye[lr_axis] - right_eye[lr_axis]))
    if eye_votes:
        lr_sign = 1 if float(np.mean(eye_votes)) > 0 else -1
        evidence["left_right_sign_source"] = "ARFaceAnchor eye transforms"
        evidence["left_right_sign_votes"] = len(eye_votes)
        evidence["left_right_sign_agreement"] = round(
            float(np.mean([np.sign(v) == np.sign(np.mean(eye_votes)) for v in eye_votes])), 3
        )
    else:
        evidence["left_right_sign_source"] = "UNRESOLVED (no eye transforms in export)"
        evidence["left_right_sign_warning"] = (
            "Subject-left vs subject-right cannot be distinguished from geometry alone. "
            "Side-specific features are suppressed. Export leftEyeTransform/rightEyeTransform "
            "from the iOS app to resolve this."
        )

    # ---- anterior axis: the nose is a skewed tail ------------------------
    remaining = [a for a in range(3) if a != lr_axis]
    skews = {}
    for axis in remaining:
        skews[axis] = float(np.mean([_skewness(to_face_local(c)[:, axis]) for c in captures]))
    ant_axis = max(remaining, key=lambda a: abs(skews[a]))
    ant_sign = 1 if skews[ant_axis] > 0 else -1
    evidence["skewness_per_remaining_axis"] = {str(a): round(v, 4) for a, v in skews.items()}
    evidence["anterior_axis"] = ant_axis

    # ---- superior axis: whatever is left --------------------------------
    sup_axis = [a for a in remaining if a != ant_axis][0]
    sup_sign = 1
    eye_above: list[float] = []
    for capture in captures:
        eyes = capture.eye_positions()
        if eyes is None:
            continue
        local = to_face_local(capture)
        midpoint = (eyes[0] + eyes[1]) / 2.0
        eye_above.append(float(midpoint[sup_axis] - local[:, sup_axis].mean()))
    if eye_above:
        sup_sign = 1 if float(np.mean(eye_above)) > 0 else -1
        evidence["superior_sign_source"] = "eye midpoint above mesh centroid"
    else:
        # Fall back on taper: the face is broader at the forehead than the chin.
        taper_votes = []
        for capture in captures:
            local = to_face_local(capture)
            coord = local[:, sup_axis]
            width = np.abs(local[:, lr_axis])
            high = coord >= np.quantile(coord, 0.75)
            low = coord <= np.quantile(coord, 0.25)
            taper_votes.append(float(width[high].mean() - width[low].mean()))
        sup_sign = 1 if float(np.mean(taper_votes)) > 0 else -1
        evidence["superior_sign_source"] = "broader end of the mesh taken as superior (forehead vs chin)"
        evidence["superior_taper_margin"] = round(float(np.mean(taper_votes)), 6)

    convention = AxisConvention(
        left=(lr_axis, lr_sign),
        superior=(sup_axis, sup_sign),
        anterior=(ant_axis, ant_sign),
        evidence=evidence,
    )

    # Keep the frame right-handed; if the detected signs make it left-handed,
    # the anterior sign is the one we are least sure of, so flip that.
    if not convention.is_right_handed():
        convention.anterior = (ant_axis, -ant_sign)
        convention.evidence["anterior_sign_flipped_for_handedness"] = True

    return convention


def default_axis_convention() -> AxisConvention | None:
    """The saved convention, or ``None`` if detection has not been run."""
    return AxisConvention.load()


