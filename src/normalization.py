def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Detect the axis convention and normalise captures.")
    sub = parser.add_subparsers(dest="command", required=True)

    p_detect = sub.add_parser("detect", help="detect the ARKit axis convention from real captures")
    p_detect.add_argument("root", nargs="?", default=str(RAW_DIR))
    p_detect.add_argument("--save", action="store_true", help="write config/axis_convention.json")
    p_detect.add_argument("--confirm", action="store_true",
                          help="mark the saved convention as visually confirmed by you")

    p_show = sub.add_parser("show", help="normalise one capture and print what happened")
    p_show.add_argument("path")
    p_show.add_argument("--origin", default="centroid", choices=ORIGIN_MODES)
    p_show.add_argument("--scale", default="centroid_size", choices=SCALE_MODES)

    args = parser.parse_args(argv)
    ensure_dirs()

    if args.command == "detect":
        captures = load_all(Path(args.root))
        if not captures:
            print(f"No loadable captures under {args.root}.")
            print("Export captures from the iOS app into data/raw/<participant_id>/ first.")
            return 1
        convention = detect_axis_convention(captures)
        print(f"Detected from {len(captures)} capture(s):\n")
        print(convention.describe())
        print("\nEvidence:")
        print(json.dumps(convention.evidence, indent=2))
        margin = convention.evidence.get("left_right_margin", 0)
        if isinstance(margin, (int, float)) and margin < 2.0:
            print("\nWARNING: the left-right axis was not clearly separated from the others")
            print("(margin < 2x). Inspect the mesh in the 3D viewer before trusting this.")
        if args.save:
            convention.confirmed_by_user = bool(args.confirm)
            path = convention.save()
            print(f"\nSaved to {path}")
            if not args.confirm:
                print("Confirm it visually (python -m src.visualization <capture> --frame),")
                print("then rerun with --save --confirm.")
        else:
            print("\n(dry run -- pass --save to write config/axis_convention.json)")
        return 0

    capture = load_capture(Path(args.path))
    config = NormalizationConfig(origin=args.origin, scale=args.scale)
    face = normalize_capture(capture, config=config)
    print(f"{face.key}")
    print(f"  origin mode      : {face.origin_mode}")
    print(f"  origin offset (m): {np.round(face.origin_offset_m, 5).tolist()}")
    print(f"  scale mode       : {face.scale_mode}")
    print(f"  scale reference  : {face.scale_reference_m:.6f} m")
    print(f"  side resolved    : {face.side_resolved}")
    lo, hi = face.vertices.min(axis=0), face.vertices.max(axis=0)
    print(f"  normalised bbox  : x[{lo[0]:+.3f},{hi[0]:+.3f}] y[{lo[1]:+.3f},{hi[1]:+.3f}] z[{lo[2]:+.3f},{hi[2]:+.3f}]")
    for note in face.notes:
        print(f"  note: {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
