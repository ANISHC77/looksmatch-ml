ORIGIN_MODES = ("centroid", "eye_midpoint", "nose_tip_extremum")
SCALE_MODES = ("centroid_size", "interocular", "none")


@dataclass
class NormalizationConfig:
    """Choices that define the normalised frame. Recorded with every output."""

    origin: str = "centroid"
    scale: str = "centroid_size"
    procrustes: bool = False

    def __post_init__(self) -> None:
        if self.origin not in ORIGIN_MODES:
            raise ValueError(f"origin must be one of {ORIGIN_MODES}, got {self.origin!r}")
        if self.scale not in SCALE_MODES:
            raise ValueError(f"scale must be one of {SCALE_MODES}, got {self.scale!r}")


@dataclass
class NormalizedFace:
    """A capture expressed in the canonical frame, plus full provenance."""

    participant_id: str
    capture_id: str
    vertices: np.ndarray           # (N, 3) in the canonical frame
    triangles: np.ndarray
    scale_reference_m: float       # the divisor used, in metres
    scale_mode: str
    origin_mode: str
    origin_offset_m: np.ndarray    # what was subtracted, pre-scaling, in metres
    axis_convention: AxisConvention
    side_resolved: bool
    eye_positions: tuple[np.ndarray, np.ndarray] | None = None
    notes: list[str] = field(default_factory=list)

    @property
    def key(self) -> str:
        return f"{self.participant_id}/{self.capture_id}"

    def in_metres(self) -> np.ndarray:
        """Undo the scale division: canonical orientation, true metric size."""
        return self.vertices * self.scale_reference_m


def to_face_local(capture: FaceCapture) -> np.ndarray:
    """Vertices in ARKit face-anchor space.

    If the exporter already wrote face-local vertices (ARKit's native output)
    this is a copy. If it wrote world-space vertices, the anchor transform is
    inverted to undo camera pose and distance.
    """
    verts = np.asarray(capture.vertices, dtype=np.float64)
    if capture.coordinate_space != "world":
        return verts.copy()
    if capture.transform is None:
        raise ValueError(
            f"{capture.key}: vertices are declared world-space but no anchor transform "
            "was exported, so head pose cannot be undone."
        )
    inverse = np.linalg.inv(capture.transform)
    homogeneous = np.column_stack([verts, np.ones(len(verts))])
    return (homogeneous @ inverse.T)[:, :3]


def _eye_positions_canonical(capture: FaceCapture, convention: AxisConvention) -> tuple[np.ndarray, np.ndarray] | None:
    eyes = capture.eye_positions()
    if eyes is None:
        return None
    return convention.apply(eyes[0]), convention.apply(eyes[1])


def normalize_capture(
    capture: FaceCapture,
    convention: AxisConvention | None = None,
    config: NormalizationConfig | None = None,
) -> NormalizedFace:
    """Apply steps [1]-[4] of the normalisation pipeline to one capture."""
    config = config or NormalizationConfig()
    if convention is None:
        convention = default_axis_convention()
        if convention is None:
            raise ValueError(
                "No axis convention available. Run `python -m src.normalization detect` "
                "once on your real captures first (it writes config/axis_convention.json)."
            )

    notes: list[str] = []
    if not convention.confirmed_by_user:
        notes.append("axis convention not yet visually confirmed (see docs/NORMALIZATION.md)")

    # [1] face-local, [2] canonical axes
    local = to_face_local(capture)
    verts = convention.apply(local)
    eyes = _eye_positions_canonical(capture, convention)
    side_resolved = bool(capture.has_eye_transforms()) or "UNRESOLVED" not in str(
        convention.evidence.get("left_right_sign_source", "")
    )
    if not side_resolved:
        notes.append("subject left/right unresolved; side-specific features suppressed")

    # [3] origin
    if config.origin == "centroid":
        origin = verts.mean(axis=0)
    elif config.origin == "eye_midpoint":
        if eyes is None:
            raise ValueError(
                f"{capture.key}: origin='eye_midpoint' needs eye transforms, which this "
                "export does not contain. Use origin='centroid'."
            )
        origin = (eyes[0] + eyes[1]) / 2.0
    else:  # nose_tip_extremum
        origin = verts[int(np.argmax(verts[:, 2]))].copy()
        notes.append("origin at the most anterior vertex (geometric extremum, not a picked landmark)")
    verts = verts - origin
    if eyes is not None:
        eyes = (eyes[0] - origin, eyes[1] - origin)

    # [4] scale
    if config.scale == "centroid_size":
        # Root-mean-square distance to the centroid: the standard scale measure
        # in geometric morphometrics. Uses every vertex, so no single noisy
        # point can move it, and it needs no landmarks.
        centred = verts - verts.mean(axis=0)
        reference = float(np.sqrt((centred ** 2).sum(axis=1).mean()))
    elif config.scale == "interocular":
        if eyes is None:
            raise ValueError(
                f"{capture.key}: scale='interocular' needs eye transforms, which this "
                "export does not contain. Use scale='centroid_size'."
            )
        reference = float(np.linalg.norm(eyes[0] - eyes[1]))
    else:
        reference = 1.0
        notes.append("no scale normalisation: values stay in metres")

    if reference <= 0:
        raise ValueError(f"{capture.key}: scale reference is {reference}, cannot normalise")
    verts = verts / reference
    if eyes is not None:
        eyes = (eyes[0] / reference, eyes[1] / reference)

    return NormalizedFace(
        participant_id=capture.participant_id,
        capture_id=capture.capture_id,
        vertices=verts,
        triangles=capture.triangles.copy(),
        scale_reference_m=reference,
        scale_mode=config.scale,
        origin_mode=config.origin,
        origin_offset_m=origin,
        axis_convention=convention,
        side_resolved=side_resolved,
        eye_positions=eyes,
        notes=notes,
    )


# -- step [5]: optional Procrustes refinement ------------------------------

def procrustes_align(source: np.ndarray, target: np.ndarray) -> np.ndarray:
    """Rotate ``source`` onto ``target`` (rotation only, no scale/reflection).

    Correspondence is by vertex INDEX, which is exact here because every capture
    in a cohort shares one ARKit topology. Classic Kabsch/orthogonal Procrustes,
    with the determinant correction that forbids reflection -- reflecting a face
    would swap its left and right sides.
    """
    src_c = source - source.mean(axis=0)
    tgt_c = target - target.mean(axis=0)
    u, _, vt = np.linalg.svd(src_c.T @ tgt_c)
    d = np.sign(np.linalg.det(vt.T @ u.T))
    correction = np.diag([1.0, 1.0, d])
    rotation = vt.T @ correction @ u.T
    return src_c @ rotation.T


def generalized_procrustes(
    faces: Sequence[NormalizedFace], iterations: int = 3, tol: float = 1e-7
) -> tuple[list[NormalizedFace], np.ndarray]:
    """Iteratively align a cohort to its own mean shape (rotation only).

    This removes RESIDUAL orientation jitter left by ARKit's tracker. It is a
    refinement of an already-good alignment, not the primary pose normalisation
    -- that came free from the face-anchor frame.
    """
    if not faces:
        return [], np.zeros((0, 3))
    counts = {f.vertices.shape[0] for f in faces}
    if len(counts) != 1:
        raise ValueError(f"Procrustes needs one shared topology; found vertex counts {counts}")

    aligned = [f.vertices.copy() for f in faces]
    mean_shape = aligned[0].copy()
    for _ in range(iterations):
        aligned = [procrustes_align(v, mean_shape) for v in aligned]
        new_mean = np.mean(aligned, axis=0)
        shift = float(np.linalg.norm(new_mean - mean_shape))
        mean_shape = new_mean
        if shift < tol:
            break

    out: list[NormalizedFace] = []
    for face, verts in zip(faces, aligned):
        refined = NormalizedFace(**{**face.__dict__, "vertices": verts})
        refined.notes = list(face.notes) + ["generalized Procrustes refinement applied"]
        out.append(refined)
    return out, mean_shape


def normalize_all(
    captures: Iterable[FaceCapture],
    convention: AxisConvention | None = None,
    config: NormalizationConfig | None = None,
) -> list[NormalizedFace]:
    config = config or NormalizationConfig()
    faces = [normalize_capture(c, convention, config) for c in captures]
    if config.procrustes and faces:
        faces, _ = generalized_procrustes(faces)
    return faces


# ==========================================================================
# CLI
